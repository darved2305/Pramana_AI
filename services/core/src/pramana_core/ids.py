"""Identifiers for production tables (ADR 0015, PRODUCTION.md §4.1).

Primary keys are UUIDv7: 128 bits, time-ordered for index locality, generated by the application.
They are shown outside the database as type-prefixed strings in the Stripe style, for example
``org_01JC4ZK3V0QY8H6T2W9N5M7R1S``: the prefix names the type, and the rest is the UUID in
Crockford base32 (26 characters). Parsing checks the prefix, so an ``inv_`` id can never be used
where an ``org_`` id is expected.
"""

from __future__ import annotations

import os
import time
import uuid

_ALPHABET = "0123456789ABCDEFGHJKMNPQRSTVWXYZ"
_DECODE = {c: i for i, c in enumerate(_ALPHABET)}
_DECODE.update({c.lower(): i for c, i in list(_DECODE.items())})

PREFIXES = frozenset(
    {"org", "site", "model", "mem", "inv", "invite", "flow", "ident", "usr", "consent"}
)


def uuid7(now_ms: int | None = None) -> uuid.UUID:
    """A version 7 UUID (RFC 9562): 48-bit Unix milliseconds, then 74 random bits."""
    ms = int(time.time() * 1000) if now_ms is None else now_ms
    if not 0 <= ms < 1 << 48:
        raise ValueError("timestamp out of range for UUIDv7")
    rand = int.from_bytes(os.urandom(10), "big")
    rand_a = rand >> 68 & 0xFFF
    rand_b = rand & ((1 << 62) - 1)
    value = ms << 80 | 0x7 << 76 | rand_a << 64 | 0b10 << 62 | rand_b
    return uuid.UUID(int=value)


def encode(prefix: str, value: uuid.UUID) -> str:
    if prefix not in PREFIXES:
        raise ValueError(f"unknown id prefix {prefix!r}")
    n = value.int
    chars = [_ALPHABET[(n >> (5 * i)) & 31] for i in range(25, -1, -1)]
    return f"{prefix}_{''.join(chars)}"


def decode(prefix: str, public_id: str) -> uuid.UUID:
    """Parse a public id. Raises ``ValueError`` for a wrong prefix or a malformed body."""
    head, sep, body = public_id.partition("_")
    if sep != "_" or head != prefix or len(body) != 26:
        raise ValueError(f"not a {prefix} id")
    n = 0
    for c in body:
        if c not in _DECODE:
            raise ValueError(f"not a {prefix} id")
        n = n << 5 | _DECODE[c]
    if n >> 128:
        raise ValueError(f"not a {prefix} id")
    return uuid.UUID(int=n)


def new(prefix: str) -> tuple[uuid.UUID, str]:
    """A fresh UUIDv7 and its public form."""
    value = uuid7()
    return value, encode(prefix, value)
