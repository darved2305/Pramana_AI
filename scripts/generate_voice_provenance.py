def _cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\r", " ").replace("\n", " ")


def _summary(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8"))
    if value.get("participants") != "synthetic voice bots":
        raise ValueError(f"{path.name} does not declare synthetic voice bots")
    if "answers" in value:
        raise ValueError(f"{path.name} contains private speech details")
    return value


def _result_text(items: list[tuple[Path, dict[str, Any]]]) -> str:
    if all(item.get("status") == "verified" for _, item in items):
        outcomes = "verified repair"
    elif all(item.get("correct") is True for _, item in items):
        outcomes = "correct decision"
    elif any(item.get("presence_checks") for _, item in items):
        outcomes = "presence-check and abstention outcomes; see notes for details"
    else:
        outcomes = "see the dated notes for the run-specific outcome"
    if all(item.get("replay_identical") is True for _, item in items):
        outcomes += "; identical replay recorded"
    return outcomes


def render_summary() -> str:
    voice_files = sorted(RUN_DIR.glob("voice-*.json"))
    summaries = [(path, _summary(path)) for path in voice_files]
    grouped: dict[str, list[tuple[Path, dict[str, Any]]]] = {}
    for path, item in summaries:
        scenario = str(item.get("scenario", "unknown"))
        variant = str(item.get("variant") or "standard")
        key = f"{scenario} {variant}"
        grouped.setdefault(key, []).append((path, item))

    lines = [
        "<!-- Generated by scripts/generate_voice_provenance.py; do not edit by hand. -->",
        "# Voice run provenance",
        "",
        "This public-safe summary uses committed run summaries and the documented integration",
        "notes. It omits audio and private transcripts. `Unknown` means the source did not record",
        "the value; it is not a positive validation result.",
        "",
        "## Committed live voice summaries",
        "",
        "The Nov 7 notes say Gnani Prisma and Timbre were live and all participants in these voice",
        "runs were synthetic bots. The JSON summaries do not record per-call model versions. The",
        (
            "integration report and current code describe Prisma v3.0 and Timbre v3.0/v2.5 "
            "routing, but that does not identify which TTS model served every call in each "
            "historical run."
        ),
        "",
        "| Date | Speakers | Model provenance | Recorded outcome | Artifact path | Unknowns |",
        "|---|---|---|---|---|---|",
    ]
    for group, items in sorted(grouped.items()):
        artifacts = "; ".join(f"`{path.relative_to(ROOT).as_posix()}`" for path, _ in items)
        outcome = _result_text(items)
        if group.startswith("S1"):
            outcome = (
                "three verified repairs; correct reveal, matching commitment, and identical replay"
            )
        elif group.startswith("S2"):
            outcome = (
                "initial run sent Hinglish phrases to English TTS; corrected run used English "
                "phrases; "
                "both decisions were correct and replay was identical"
            )
        elif group == "S7 honest":
            outcome = "honest label passed; investigation abstained; identical replay recorded"
        elif group.startswith("S7 adversary"):
            outcome = (
                "first attempt stopped before a presence check; corrected retry failed the label "
                "check and abstained; identical replay recorded"
            )
        lines.append(
            "| "
            + " | ".join(
                _cell(value)
                for value in (
                    "2026-11-07",
                    "Synthetic voice bots",
                    "Live Gnani Prisma and Timbre; exact per-call versions are not in JSON",
                    outcome,
                    artifacts,
                    "No public audio or transcripts; no human speaker in these runs.",
                )
            )
            + " |"
        )

    lines.extend(
        [
            "",
            "## Earlier runs recorded in prose only",
            "",
            "The table below is generated from the documented run descriptions in",
            (
                "`docs/engineering/GNANI_INTEGRATION.md`. The source does not include "
                "run-specific JSON for these entries."
            ),
            "The mixed phone run is the only documented human voice run in this",
            "set; it does not establish broad speech quality or noise robustness.",
            "",
            "| Date | Speakers | Model provenance | Recorded outcome | Artifact path | Unknowns |",
            "|---|---|---|---|---|---|",
        ]
    )
    for run in DOCUMENTED_RUNS:
        lines.append("| " + " | ".join(_cell(str(run[key])) for key in run) + " |")

    lines.extend(
        [
            "",
            "## Boundaries",
            "",
            "The committed Nov 7 voice summaries and the older run notes are integration evidence,",
            "not a current live-provider check. They do not prove native-speaker approval, broad",
            "telephone-noise performance, or public-demo consent. Speech accuracy and latency are",
            "not reported here. The current local text rehearsal is not a voice run; see",
            "[DEMO.md](../DEMO.md) and its committed local timeline.",
            "",
        ]
    )
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate the public-safe voice provenance summary"
    )
    parser.add_argument(
        "--check", action="store_true", help="fail if the committed summary is stale"
    )
    args = parser.parse_args(argv)
    output = render_summary()
    if args.check:
        current = (
            OUTPUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUTPUT.exists() else ""
        )
        if current != output:
            print(f"{OUTPUT.name} is out of date; run without --check", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(output, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
