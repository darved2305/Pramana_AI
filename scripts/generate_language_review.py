"""Generate the Hindi and Marathi spoken-question review sheet."""

from __future__ import annotations

from pathlib import Path

from pramana_contracts import ProbeAction, TemplateLanguage
from pramana_core.language.realize import CONFIRM_PREFIX, realize
from pramana_core.language.speakable import speakable
from pramana_domain import load_pack

LANGUAGES: tuple[TemplateLanguage, ...] = ("hi", "mr")
OUTPUT = Path(__file__).resolve().parents[1] / "docs" / "engineering" / "LANGUAGE_REVIEW.md"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render_review_sheet() -> str:
    pack = load_pack("campus_block_c")
    lines = [
        "<!-- Generated by scripts/generate_language_review.py. "
        "Regenerate with: uv run python scripts/generate_language_review.py -->",
        "# Hindi and Marathi language review",
        "",
        "Native-speaker review is pending. Leave the reviewer column blank until a reviewer has "
        "checked the wording and pronunciation.",
        "",
        "Each probe and valid location is listed in direct, move, confirmation, and "
        "move-confirmation forms. Display text is the participant-visible line. Spoken text is "
        "the output of `speakable()` sent to Timbre.",
        "",
        "| Language | Probe | Location | Form | Display text | Spoken text | Reviewer |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for probe in pack.probes:
        for binding in probe.observes:
            for language in LANGUAGES:
                for requires_move in (False, True):
                    action = ProbeAction(
                        participant_id="p_review",
                        probe_id=probe.id,
                        location_id=binding.at,
                        requires_move=requires_move,
                    )
                    base = realize(pack, action, language)
                    for confirmation in (False, True):
                        display = (
                            f"{CONFIRM_PREFIX[language]} {base}".strip() if confirmation else base
                        )
                        form = "move" if requires_move else "direct"
                        if confirmation:
                            form = f"{form} confirmation"
                        spoken = speakable(display, language)
                        lines.append(
                            "| "
                            + " | ".join(
                                (
                                    language,
                                    probe.id,
                                    binding.at,
                                    form,
                                    _cell(display),
                                    _cell(spoken),
                                    "",
                                )
                            )
                            + " |"
                        )
    return "\n".join(lines) + "\n"


def main() -> None:
    OUTPUT.write_text(render_review_sheet(), encoding="utf-8")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
