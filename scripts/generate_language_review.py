"""Generate the Hindi and Marathi review sheet for native speakers.

    uv run python scripts/generate_language_review.py           # write the sheet
    uv run python scripts/generate_language_review.py --check   # fail if it is out of date

Every spoken question in the pack, in each form a participant can hear it (asked where they
stand, asked to walk there, the confirmation re-ask, and the presence check), with the text
shown on screen and the text actually sent to Timbre after ``speakable()``. The reviewer
column stays blank until a native speaker has checked that line: an AI review is not one.
Ported from the earlier nikhil/presence-challenges branch and extended with presence checks.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from pramana_contracts import ProbeAction, TemplateLanguage
from pramana_core.language.realize import CONFIRM_PREFIX, realize, realize_challenge
from pramana_core.language.speakable import speakable
from pramana_domain import load_pack

LANGUAGES: tuple[TemplateLanguage, ...] = ("hi", "mr")
OUTPUT = Path(__file__).resolve().parents[1] / "docs" / "engineering" / "LANGUAGE_REVIEW.md"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _row(*cells: str) -> str:
    return "| " + " | ".join(_cell(c) for c in cells) + " |"


def render_review_sheet() -> str:
    pack = load_pack("campus_block_c")
    lines = [
        "<!-- Generated by scripts/generate_language_review.py; do not edit by hand. -->",
        "# Hindi and Marathi language review",
        "",
        "**Native-speaker review is pending.** A reviewer writes their role (not their name), the",
        "date and OK or a corrected line in the last column, for display and spoken text alike.",
        "Accepted corrections go into `packs/campus_block_c.yaml` as commits that keep",
        "`services/core/tests/test_template_lint.py` passing; then regenerate this sheet.",
        "",
        "Display text is what the participant sees. Spoken text is what is sent to Timbre after",
        "`speakable()` rewrites equipment codes so they are read the way people say them.",
        "",
        "| Language | Item | Place | Form | Display text | Spoken text | Reviewer |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for language in LANGUAGES:
        for probe in pack.probes:
            for binding in probe.observes:
                for requires_move in (False, True):
                    action = ProbeAction(
                        participant_id="p_review",
                        probe_id=probe.id,
                        location_id=binding.at,
                        requires_move=requires_move,
                    )
                    base = realize(pack, action, language)
                    for confirmation in (False, True):
                        # Exactly as the core builds the re-ask (InvestigationService).
                        display = CONFIRM_PREFIX[language] + base if confirmation else base
                        form = ("move" if requires_move else "direct") + (
                            " confirmation" if confirmation else ""
                        )
                        spoken = speakable(display, language)
                        lines.append(
                            _row(language, probe.id, binding.at, form, display, spoken, "")
                        )
        for token in pack.presence_tokens:
            display = realize_challenge(pack, token.id, token.at, language)
            lines.append(
                _row(
                    language,
                    token.id,
                    token.at,
                    "presence check",
                    display,
                    speakable(display, language),
                    "",
                )
            )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Hindi and Marathi review sheet")
    ap.add_argument("--check", action="store_true", help="fail if the committed sheet is stale")
    args = ap.parse_args(argv)
    sheet = render_review_sheet()
    if args.check:
        current = (
            OUTPUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUTPUT.exists() else ""
        )
        if current != sheet:
            print(f"{OUTPUT.name} is out of date; run without --check", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(sheet, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
