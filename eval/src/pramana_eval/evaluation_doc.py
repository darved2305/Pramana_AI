"""Fill the results section of docs/EVALUATION.md from a generated ``summary.json``.

    uv run python -m pramana_eval.evaluation_doc eval/reports/benchmark-2026-11-07-rc1
    uv run python -m pramana_eval.evaluation_doc eval/reports/benchmark-2026-11-07-rc1 --check

Only the text between the results markers is replaced, and every number comes from the
summary. The deviations from the pre-registered plan are stated with the table, not hidden.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[3]
DOC = ROOT / "docs" / "EVALUATION.md"
START = "<!-- results:start (generated by pramana_eval.evaluation_doc; do not edit) -->"
END = "<!-- results:end -->"
LABEL = {
    "E_ours": "E (ours, K=1)",
    "E_parallel3": "E (ours, K=3)",
    "A_checklist": "A checklist",
    "C_random": "C random",
    "D_greedy_entropy": "D greedy entropy",
    "E-no_decision_focus": "E without decision focus",
    "E-no_cost": "E without effort cost",
    "B_llm": "B LLM",
}


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x * 100:.1f}%"


def _num(x: float | None, digits: int = 1) -> str:
    return "n/a" if x is None else f"{x:.{digits}f}"


def _ci(d: dict[str, float], scale: float = 1.0, digits: int = 3) -> str:
    if d.get("mean") is None:
        return "n/a"

    def f(v: float) -> str:
        return f"{v * scale:+.{digits}f}"

    return f"{f(d['mean'])} [{f(d['ci95_low'])}, {f(d['ci95_high'])}]"


def render(summary: dict[str, Any], source: str) -> str:
    seeds = summary["seeds"]
    n = {k: int(v["n"]) for k, v in summary["policies"].items()}
    mix = ", ".join(f"{k} {v}" for k, v in summary["scenario_mix"].items())
    lines = [
        START,
        "",
        f"Source: `{source}/summary.json`, commit `{summary['git_sha']}`, seeds "
        f"{seeds[0]}-{seeds[1]} ({max(n.values())} scenarios: {mix}), logic mode (structured "
        "answers from simulated participants; no Gnani or LLM calls).",
        "",
        "| Policy | n (failed) | Historical success | Honest success | Decision accuracy | "
        "Diagnostic probes (median) | Diagnostic effort s (mean) | False confidence | "
        "Unidentifiable recall | Historical abstention precision | Justified abstention P/R |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for key, p in summary["policies"].items():
        lines.append(
            f"| {LABEL.get(key, key)} | {int(p['n'])} ({int(p['failed_runs'])}) | "
            f"{_pct(p['success_rate'])} | {_pct(p.get('honest_success_rate'))} | "
            f"{_pct(p['decision_accuracy'])} | "
            f"{_num(p['probes_median'])} | {_num(p['effort_s_mean'], 0)} | "
            f"{_pct(p['false_confidence_rate'])} | {_pct(p['abstention_recall'])} | "
            f"{_pct(p['abstention_precision'])} | "
            f"{_pct(p.get('justified_abstention_precision'))} / "
            f"{_pct(p.get('justified_abstention_recall'))} |"
        )
    lines += [
        "",
        "Paired differences E minus X, mean with bootstrap 95% CI. Success in percentage points; "
        "the intervals are descriptive and do not replace the adjusted paired tests below.",
        "",
        "| Versus | Historical success (points) | Honest success (points) | Probes | Effort s |",
        "|---|---|---|---|---|",
    ]
    for key, d in summary["paired_vs_E"].items():
        lines.append(
            f"| {LABEL.get(key, key)} | {_ci(d['success'], 100, 1)} | "
            f"{_ci(d.get('honest_success', {}), 100, 1)} | "
            f"{_ci(d['probes'], 1, 2)} | {_ci(d['effort_s'], 1, 0)} |"
        )
    lines += [
        "",
        "**Deviations from the pre-registered plan above, stated rather than hidden:**",
        "",
    ]
    if "protocol" in summary:
        protocol = summary["protocol"]
        lines += [
            "- The run followed the frozen protocol `" + protocol["path"] + "`, which pins code "
            f"`{protocol['frozen_code_commit']}` and seeds {seeds[0]}-{seeds[1]}.",
            "- Statistical p-values below use the registered paired tests and Holm correction. "
            "Bootstrap intervals remain descriptive.",
        ]
        lines += [f"- Protocol deviation: {item}" for item in protocol.get("deviations", [])]
    else:
        lines += [
            "- These RC1 seeds were examined before the stated freeze; this analysis is "
            "exploratory. The historical success metric credits pair abstention and does not "
            "measure resolution of both faults.",
            "- The registered McNemar, Wilcoxon and Holm analyses were not run for this artifact. "
            "No adjusted significance claim follows from its bootstrap intervals.",
            "- The historical artifact does not contain an honest-success rate or the newer "
            "calibration and stratum denominators; these are shown as unavailable.",
        ]
    lines += [
        "",
        "Pair outcomes, calibration and stratum counts are reported separately below.",
        "",
        "| Policy | Pair n | First useful action | Full pair resolution | "
        "Resolution n | Mean repairs | Verification probes | Justified abstentions | "
        "Unknown-identifiability abstentions |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for key, p in summary["policies"].items():
        lines.append(
            f"| {LABEL.get(key, key)} | {p.get('pair_outcome_denominator', 'n/a')} | "
            f"{_pct(p.get('pair_first_useful_action_rate'))} | "
            f"{_pct(p.get('pair_full_resolution_rate'))} | "
            f"{p.get('pair_resolution_denominator', 'n/a')} | "
            f"{_num(p.get('pair_repairs_mean'))} | "
            f"{_num(p.get('pair_resolution_extra_probes_mean'))} | "
            f"{p.get('justified_abstentions', 'n/a')} | "
            f"{p.get('abstentions_with_unknown_identifiability', 'n/a')} |"
        )
    if "primary_tests" in summary:
        lines += [
            "",
            "Registered paired tests (Holm adjusted within the five-comparison family). "
            "Success means correct decision or abstention only when identifiable is false; "
            "pair abstention does not count.",
            "",
            "| Outcome | Comparison | Paired n | p | Holm p |",
            "|---|---|---:|---:|---:|",
        ]
        for field, comparisons in summary["primary_tests"].items():
            if field == "success_definition":
                continue
            for key, result in comparisons.items():
                p_raw = "n/a" if result["p"] is None else f"{result['p']:.6g}"
                p_holm = "n/a" if result["p_holm"] is None else f"{result['p_holm']:.6g}"
                lines.append(
                    f"| {field} | E vs {LABEL.get(key, key)} | {result['n']} | {p_raw} | {p_holm} |"
                )
        sig = [
            LABEL.get(key, key)
            for key, result in summary["primary_tests"]["success"].items()
            if key != "success_definition"
            and result["p_holm"] is not None
            and result["p_holm"] < 0.05
        ]
        lines += [
            "",
            "Adjusted success comparisons below 0.05: " + (", ".join(sig) if sig else "none"),
        ]
    if "budget_curves" in summary:
        lines += [
            "",
            "Fixed-question and matched-effort curves, including scenario bootstrap intervals, "
            "are in `budget-curves.json` and the paired SVG files. The reliability diagram with "
            "bin counts is `reliability-diagram.svg`; `scenario-manifest.json` gives generated "
            "stratum and behavior counts.",
        ]
    lines += ["", END]
    return "\n".join(lines)


def splice(doc: str, block: str) -> str:
    if START in doc:
        head, rest = doc.split(START, 1)
        tail = rest.split(END, 1)[1]
        return head + block + tail
    return doc.rstrip("\n") + "\n\n### Results\n\n" + block + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("report", help="report folder holding summary.json")
    ap.add_argument("--check", action="store_true", help="fail if the doc is out of date")
    args = ap.parse_args(argv)
    folder = Path(args.report)
    summary = json.loads((folder / "summary.json").read_text(encoding="utf-8"))
    source = (
        folder.resolve().relative_to(ROOT).as_posix()
        if folder.resolve().is_relative_to(ROOT)
        else str(folder)
    )
    doc = DOC.read_text(encoding="utf-8").replace("\r\n", "\n")
    updated = splice(doc, render(summary, source))
    if args.check:
        if updated != doc:
            print(
                "docs/EVALUATION.md results are out of date; run without --check", file=sys.stderr
            )
            return 1
        return 0
    DOC.write_text(updated, encoding="utf-8", newline="\n")
    print(f"updated {DOC.relative_to(ROOT)} from {source}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
